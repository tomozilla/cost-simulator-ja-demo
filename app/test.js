const S = require("./sim.js");
const data = require("./rates.json");
const base = { plan: "pro", projects: 1, compute: "micro", pitr: 0, domains: 0, usage: { dbGb: 1, egressGb: 10, cachedGb: 5, storageGb: 5, mau: 1000, rtMessagesM: 0.1, rtPeak: 20, edgeM: 0.1 } };
let fail = 0;
const eq = (name, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) fail++; console.log(ok ? "ok  " : "FAIL", name, ok ? "" : JSON.stringify(got) + " != " + JSON.stringify(want)); };
const r0 = S.simulate(base, data);
eq("quiet month: pro single micro = 25", [r0.capOn.total, r0.capOff.total], [25, 25]);
eq("quiet month: nothing restricted", r0.blocked, []);
const spike = S.simulate({ ...base, usage: { ...base.usage, egressGb: 600 } }, data);
eq("egress 600GB: cap off adds 350*0.09 = 31.5", spike.capOff.total, 56.5);
eq("egress 600GB: cap on stays 25 but egress is restricted", [spike.capOn.total, spike.blocked], [25, ["Egress (GB)"]]);
const comp = S.simulate({ ...base, projects: 3, compute: "medium" }, data);
eq("compute is NOT capped: 3 medium = 25 + 180 - 10 = 195 either way", [comp.capOn.total, comp.capOff.total], [195, 195]);
const pitr = S.simulate({ ...base, pitr: 1 }, data);
eq("PITR is NOT capped: 125 either way", [pitr.capOn.total, pitr.capOff.total], [125, 125]);
eq("custom domain is NOT capped: +10", S.simulate({ ...base, domains: 1 }, data).capOn.total, 35);
eq("MAU 120k: cap off adds 20000*0.00325 = 65", S.simulate({ ...base, usage: { ...base.usage, mau: 120000 } }, data).capOff.total, 90);
eq("db included scales per project", S.simulate({ ...base, projects: 2, usage: { ...base.usage, dbGb: 15 } }, data).blocked, []);
eq("db over per-project allowance is flagged", S.simulate({ ...base, projects: 2, usage: { ...base.usage, dbGb: 17 } }, data).blocked, ["Database size (GB, total)"]);
eq("exactly at quota is not over", S.simulate({ ...base, usage: { ...base.usage, egressGb: 250 } }, data).blocked, []);
eq("team: no spend cap", S.simulate({ ...base, plan: "team" }, data).hasCap, false);
eq("team: no cap-ON scenario", S.simulate({ ...base, plan: "team" }, data).capOn, null);
eq("team: overage is billed (MAU 120k: 599 plan + 65 overage, Micro covered by the credit)", S.simulate({ ...base, plan: "team", usage: { ...base.usage, mau: 120000 } }, data).capOff.total, 664);
eq("pro: has spend cap", S.simulate(base, data).hasCap, true);
eq("scale helper", S.scale({ egressGb: 10, mau: 5 }, 10, ["egressGb"]), { egressGb: 100, mau: 5 });
eq("unknown plan throws", (() => { try { S.simulate({ ...base, plan: "x" }, data); } catch (e) { return /Unknown plan/.test(e.message); } })(), true);
process.exit(fail ? 1 : 0);
